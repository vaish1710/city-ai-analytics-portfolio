"""python src/demo_data.py -> outputs/demo_data.json (+ outputs/study/summary.png). One synthetic city, three history lengths."""
import json, sys
from pathlib import Path
import numpy as np, pandas as pd
import matplotlib; matplotlib.use("Agg")
import matplotlib.pyplot as plt
sys.path.insert(0, str(Path(__file__).parent))
import world as W
from study import systems

OUT = Path(__file__).resolve().parent.parent / "outputs"
SEED = 5


def city(window):
    d = W.make_world(seed=SEED, window=window)
    cut = int(d.storm.max() * 0.7); tr, te = d[d.storm <= cut].copy(), d[d.storm > cut].copy()
    sc = systems(tr, te, SEED)
    te = te.sort_values(["storm", "segment"]).reset_index(drop=True)
    # te was re-sorted above, so recompute scores on the sorted frame to keep rows aligned
    sc = systems(tr, te, SEED)
    storms = []
    for s, g in te.groupby("storm"):
        ix = g.index.values
        storms.append({"id": int(s), "forecast_in": round(float(g.total_fc.iloc[0]), 2),
                       "incident": g.incident.astype(int).tolist(), "flooded": g.flooded.astype(int).tolist(),
                       "model": np.round(sc["model (logistic)"][ix], 8).tolist(),
                       "hotspot": np.round(sc["hotspot (count)"][ix], 3).tolist(),
                       "elevation": np.round(sc["lowest elevation"][ix], 4).tolist()})
    seg = te[te.storm == te.storm.min()].sort_values("segment")
    segs = [{"id": int(r.segment), "basin": int(r.basin), "elev_ft": round(float(r.elev_ft), 1), "tidal": int(r.tidal)} for r in seg.itertuples()]
    return {"storms": storms, "segments": segs}


def main():
    data = {"note": "Synthetic city generated by src/world.py. Not Chesapeake data.", "seed": SEED,
            "cities": {("all" if w is None else str(w)): city(w) for w in (3, 12, None)}}
    (OUT / "demo_data.json").write_text(json.dumps(data, separators=(",", ":")))
    print("demo_data.json", round((OUT / "demo_data.json").stat().st_size / 1024), "KB")

    d = pd.read_csv(OUT / "study" / "by_world.csv")
    r = d[d.scenario.str.startswith("history")].copy()
    r["w"] = r.scenario.str.extract(r"= (\w+) storms")[0]
    order = ["3", "6", "12", "24", "all"]
    fig, ax = plt.subplots(figsize=(7, 4), dpi=160)
    for sysn, c, lab in [("model (logistic)", "#1f6f8b", "Model (logistic)"), ("hotspot (count)", "#d1495b", "Hotspot: count of past floods"),
                         ("lowest elevation", "#8d99ae", "Lowest elevation"), ("ceiling (true risk; unattainable)", "#bbbbbb", "Ceiling (true risk)")]:
        g = r[r.system == sysn].groupby("w").recall_reported.agg(["mean", lambda x: x.std(ddof=1) / np.sqrt(len(x))]).loc[order]
        ax.errorbar(order, g["mean"], yerr=g.iloc[:, 1], marker="o", color=c, label=lab, capsize=3, ls="--" if "Ceiling" in lab else "-")
    ax.set_xlabel("Storms of history available (all = every earlier storm)"); ax.set_ylabel("Recall of reported incidents, top 8 segments")
    ax.set_title("Model vs hotspot by history length (synthetic, 16 cities, ±1 s.e.)", fontsize=10)
    ax.legend(fontsize=8, frameon=False); ax.spines[["top", "right"]].set_visible(False)
    fig.tight_layout(); fig.savefig(OUT / "study" / "history_sweep.png"); print("chart saved")


if __name__ == "__main__":
    main()
